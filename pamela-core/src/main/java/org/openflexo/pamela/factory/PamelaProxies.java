package org.openflexo.pamela.factory;

/**
 * Tells whether an object is a PAMELA proxy, and gives access to its {@link ProxyMethodHandler}.<br>
 * 
 * Use this class instead of the types of the bytecode library generating the proxies, which is an implementation detail of PAMELA.
 * 
 * @author sylvain
 * 
 */
public final class PamelaProxies {

	private PamelaProxies() {
	}

	/**
	 * Return a flag indicating if supplied object is a proxy generated by PAMELA (a PAMELA instance, or a partial implementation of one)
	 * 
	 * @param object
	 * @return
	 */
	public static boolean isProxy(Object object) {
		return object instanceof PamelaProxy;
	}

	/**
	 * Return the {@link ProxyMethodHandler} of supplied PAMELA instance
	 * 
	 * @param object
	 * @return the handler, or null when supplied object is not a PAMELA instance (null, not a proxy, or a partial implementation)
	 */
	@SuppressWarnings("unchecked")
	public static <I> ProxyMethodHandler<I> handlerOf(Object object) {
		PamelaMethodHandler handler = methodHandlerOf(object);
		if (handler instanceof ProxyMethodHandler) {
			return (ProxyMethodHandler<I>) handler;
		}
		return null;
	}

	/**
	 * Return the {@link PamelaMethodHandler} of supplied proxy, whatever the backend that generated it
	 * 
	 * @param object
	 * @return the handler, or null when supplied object is not a PAMELA proxy
	 */
	static PamelaMethodHandler methodHandlerOf(Object object) {
		if (object instanceof PamelaProxy) {
			return ((PamelaProxy) object).pamela$getHandler();
		}
		return null;
	}

}
